#define SCR_W 480
#define SCR_H 320
#define BAR_H 36

static lv_obj_t *s_time, *s_sec, *s_date, *s_ntp;
static lv_obj_t *s_vol, *s_vol_lbl;
static lv_obj_t *s_bat, *s_wifi;
static lv_obj_t *s_temp, *s_cond, *s_detail, *s_upd;
static lv_obj_t *s_city;
static lv_obj_t *s_fore_date[WEATHER_DAILY_DAYS];
static lv_obj_t *s_fore_cond[WEATHER_DAILY_DAYS];
static lv_obj_t *s_fore_temp[WEATHER_DAILY_DAYS];
static int s_vol_val;
static bool s_vol_sync;

static const char *TAG = "clock_ui";
volatile uint32_t g_ui_heartbeat;

/* Custom CJK font subset, generated by lv_font_conv from Noto Sans CJK SC
 * (SIL Open Font License 1.1); it contains exactly the characters used below
 * plus ASCII 0x20-0x7E. The built-in LVGL CJK fonts miss several common
 * glyphs (云/阴/湿/风...). Regenerate with:
 *   lv_font_conv --font NotoSansCJKsc-Regular.otf --size 16 --bpp 4 \
 *     --format lvgl --no-compress --no-kerning --range 0x20-0x7e \
 *     --symbols <见文件头> --lv-font-name font_cn_16 --lv-include lvgl.h \
 *     -o main/font_cn_16.c */
LV_FONT_DECLARE(font_cn_16);
LV_FONT_DECLARE(font_cn_14);

#define FONT_CN     (&font_cn_16)
#define FONT_CN_SM  (&font_cn_14)
#define FONT_NUM    (&lv_font_montserrat_48)
#define FONT_SM     (&lv_font_montserrat_24)
#define FONT_TINY   (&lv_font_montserrat_14)

static const char *wx_text(int code)
{
    if (code == 0) return "晴";
    if (code == 1) return "晴间多云";
    if (code == 2) return "多云";
    if (code == 3) return "阴";
    if (code == 45 || code == 48) return "雾";
    if (code >= 51 && code <= 57) return "毛毛雨";
    if (code >= 61 && code <= 67) return "雨";
    if (code >= 71 && code <= 77) return "雪";
    if (code >= 80 && code <= 82) return "阵雨";
    if (code >= 95) return "雷雨";
    return "未知";
}

static const char *wday_text(int wday)
{
    static const char *d[] = {"周日", "周一", "周二", "周三", "周四", "周五", "周六"};
    return d[wday % 7];
}

static lv_obj_t *make_label(lv_obj_t *parent, const lv_font_t *font, uint32_t color,
                            lv_align_t align, int x, int y, const char *txt)
{
    lv_obj_t *l = lv_label_create(parent);
    lv_obj_set_style_text_font(l, font, 0);
    lv_obj_set_style_text_color(l, lv_color_hex(color), 0);
    lv_label_set_text(l, txt);
    lv_obj_align(l, align, x, y);
    return l;
}

static void update_vol_widgets(int vol)
{
    s_vol_val = vol;
    if (s_vol) {
        lv_slider_set_value(s_vol, vol, LV_ANIM_OFF);
    }
    if (s_vol_lbl) {
        char buf[16];
        snprintf(buf, sizeof(buf), "音量 %d", vol);
        lv_label_set_text(s_vol_lbl, buf);
    }
}

static void vol_cb(lv_event_t *e)
{
    if (s_vol_sync) {
        return;
    }
    int vol = (int)lv_slider_get_value(lv_event_get_target(e));
    update_vol_widgets(vol);
    ui_sync_volume(vol);
}

void clock_ui_set_volume(int vol)
{
    if (vol < 0) vol = 0;
    if (vol > 100) vol = 100;
    s_vol_sync = true;
    update_vol_widgets(vol);
    s_vol_sync = false;
}

static void update_status(void)
{
    char buf[32];
    float v = battery_volts();
    int pct = battery_percent();
    if (v > 0 && pct >= 0) {
        snprintf(buf, sizeof(buf), "%.2fV %d%%", (double)v, pct);
        lv_label_set_text(s_bat, buf);
    } else {
        lv_label_set_text(s_bat, "电量 --");
    }

    int rssi = wifi_app_rssi();
    switch (wifi_app_state()) {
    case WIFI_APP_CONNECTED:
        snprintf(buf, sizeof(buf), "WiFi %d dBm", rssi);
        lv_label_set_text(s_wifi, buf);
        rgb_set(0, 14, 0);
        break;
    case WIFI_APP_CONNECTING:
        lv_label_set_text(s_wifi, "连接中...");
        rgb_set(0, 0, 14);
        break;
    case WIFI_APP_FAILED:
        lv_label_set_text(s_wifi, "WiFi 失败");
        rgb_set(14, 0, 0);
        break;
    default:
        lv_label_set_text(s_wifi, "WiFi 关闭");
        rgb_set(6, 6, 0);
        break;
    }

    lv_label_set_text(s_ntp, wifi_app_time_synced() ? "已同步" : "对时中...");
}

static void update_weather(void)
{
    const weather_data_t *wx = weather_get();
    if (!wx->valid) {
        lv_label_set_text(s_cond, "加载中...");
        return;
    }

    char buf[32];
    snprintf(buf, sizeof(buf), "%.1f°C", (double)wx->temp);
    lv_label_set_text(s_temp, buf);

    lv_label_set_text(s_city, wx->city[0] ? wx->city : settings_get()->wx_city);
    lv_label_set_text(s_cond, wx->desc[0] ? wx->desc : wx_text(wx->code));

    if (wx->wind >= 0) {
        snprintf(buf, sizeof(buf), "湿度 %d%%   风速 %.0f km/h", wx->humidity, (double)wx->wind);
    } else {
        snprintf(buf, sizeof(buf), "湿度 %d%%", wx->humidity);
    }
    lv_label_set_text(s_detail, buf);

    for (int i = 0; i < WEATHER_DAILY_DAYS; i++) {
        lv_label_set_text(s_fore_date[i], wx->daily[i].date);
        lv_label_set_text(s_fore_cond[i],
                          wx->daily[i].desc[0] ? wx->daily[i].desc : wx_text(wx->daily[i].code));
        snprintf(buf, sizeof(buf), "%.0f°C/%.0f°C", (double)wx->daily[i].tmax,
                 (double)wx->daily[i].tmin);
        lv_label_set_text(s_fore_temp[i], buf);
    }

    time_t now;
    time(&now);
    struct tm tm;
    localtime_r(&now, &tm);
    snprintf(buf, sizeof(buf), "更新 %02d:%02d", tm.tm_hour, tm.tm_min);
    lv_label_set_text(s_upd, buf);
}

/* 1 s LVGL timer: clock every tick, status every 5 s, weather on new data */
static void tick_cb(lv_timer_t *t)
{
    (void)t;
    g_ui_heartbeat++;

    /* This log runs inside the LVGL task. If it stops while the radio task
     * keeps printing frames, the LVGL task is stalled (not the whole chip). */
    static int mem_tick;
    if (++mem_tick >= 10) {
        mem_tick = 0;
        lv_mem_monitor_t mon;
        lv_mem_monitor(&mon);
        ESP_LOGI(TAG, "UI alive: lvgl used %u/%u (%u%%), frag %u%%, max %u; "
                      "int heap %u (min %u), psram %u",
                 (unsigned)(mon.total_size - mon.free_size),
                 (unsigned)mon.total_size, (unsigned)mon.used_pct,
                 (unsigned)mon.frag_pct, (unsigned)mon.max_used,
                 (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL),
                 (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL),
                 (unsigned)heap_caps_get_free_size(MALLOC_CAP_SPIRAM));
        ui_perf_log(TAG);
    }

    time_t now;
    time(&now);
    struct tm tm;
    localtime_r(&now, &tm);

    char buf[48];
    snprintf(buf, sizeof(buf), "%02d:%02d", tm.tm_hour, tm.tm_min);
    lv_label_set_text(s_time, buf);
    snprintf(buf, sizeof(buf), "%02d", tm.tm_sec);
    lv_label_set_text(s_sec, buf);
    snprintf(buf, sizeof(buf), "%s %04d-%02d-%02d", wday_text(tm.tm_wday),
             tm.tm_year + 1900, tm.tm_mon + 1, tm.tm_mday);
    lv_label_set_text(s_date, buf);

    static int n;
    if (++n % 5 == 0) {
        update_status();
    }
    static uint32_t last_wx;
    if (weather_version() != last_wx) {
        last_wx = weather_version();
        update_weather();
    }
}

static lv_obj_t *s_tileview;

/* Use the uploaded picture (if any) as the screen background. */
void clock_ui_apply_wallpaper(void)
{
    lv_obj_t *scr = lv_screen_active();
    if (scr == NULL) {
        return;
    }
    const lv_image_dsc_t *img = wallpaper_image();
    lv_obj_set_style_bg_image_src(scr, img, 0);
    /* With a picture the solid fill would be painted underneath it and then be
     * covered: skip it, that is a few ms per full repaint. */
    lv_obj_set_style_bg_opa(scr, img ? LV_OPA_TRANSP : LV_OPA_COVER, 0);
    lv_obj_invalidate(scr);
}

lv_obj_t *clock_ui_tileview(void)
{
    return s_tileview;
}

void clock_ui_build(void)
{
    lv_obj_t *scr = lv_screen_active();
    lv_obj_set_style_bg_color(scr, lv_color_hex(0x0b1b33), 0);
    clock_ui_apply_wallpaper();

    /* status bar */
    s_bat = make_label(scr, FONT_CN_SM, 0x24d17e, LV_ALIGN_TOP_LEFT, 12, 8, "电量 --");
    s_wifi = make_label(scr, FONT_CN_SM, 0x8ec5ff, LV_ALIGN_TOP_RIGHT, -12, 8, "WiFi ...");

    /* two swipeable pages (landscape 480x284 each) */
    lv_obj_t *tv = lv_tileview_create(scr);
    s_tileview = tv;
    lv_obj_set_size(tv, SCR_W, SCR_H - BAR_H);
    lv_obj_align(tv, LV_ALIGN_BOTTOM_MID, 0, 0);
    lv_obj_set_style_bg_opa(tv, LV_OPA_TRANSP, 0);
    lv_obj_set_scrollbar_mode(tv, LV_SCROLLBAR_MODE_OFF);
    lv_obj_t *tile_clock = lv_tileview_add_tile(tv, 0, 0, LV_DIR_HOR);
    lv_obj_t *tile_wx = lv_tileview_add_tile(tv, 1, 0, LV_DIR_HOR);
    lv_obj_t *tile_radio = lv_tileview_add_tile(tv, 2, 0, LV_DIR_HOR);

    /* clock page */
    s_time = make_label(tile_clock, FONT_NUM, 0xffffff, LV_ALIGN_TOP_MID, 0, 18, "--:--");
    s_sec = make_label(tile_clock, FONT_SM, 0x00c2ff, LV_ALIGN_TOP_MID, 0, 82, "--");
    s_date = make_label(tile_clock, FONT_CN, 0xffd479, LV_ALIGN_TOP_MID, 0, 116, "----");
    s_ntp = make_label(tile_clock, FONT_CN_SM, 0x6f86a6, LV_ALIGN_TOP_MID, 0, 146, "对时中...");

    s_vol_lbl = make_label(tile_clock, FONT_CN_SM, 0x8ec5ff, LV_ALIGN_TOP_LEFT, 28, 196, "音量 70");
    s_vol = lv_slider_create(tile_clock);
    lv_obj_set_size(s_vol, 240, 14);
    lv_obj_align(s_vol, LV_ALIGN_TOP_LEFT, 190, 200);
    lv_slider_set_range(s_vol, 0, 100);
    s_vol_val = audio_get_vol();
    lv_slider_set_value(s_vol, s_vol_val, LV_ANIM_OFF);
    lv_obj_set_style_bg_color(s_vol, lv_color_hex(0x223a5e), LV_PART_MAIN);
    lv_obj_set_style_bg_color(s_vol, lv_color_hex(0x00c2ff), LV_PART_INDICATOR);
    lv_obj_add_event_cb(s_vol, vol_cb, LV_EVENT_VALUE_CHANGED, NULL);
    /* Keep this string inside font_cn_14's subset. The radio page is one more
     * horizontal swipe to the left. */
    make_label(tile_clock, FONT_CN_SM, 0x46586f, LV_ALIGN_BOTTOM_MID, 0, -8,
               "左右滑动查看天气");

    /* weather page: current conditions on the left, 3-day forecast on the right */
    s_city = make_label(tile_wx, FONT_CN, 0xffffff, LV_ALIGN_TOP_LEFT, 28, 10,
                        settings_get()->wx_city);
    s_temp = make_label(tile_wx, FONT_NUM, 0xffffff, LV_ALIGN_TOP_LEFT, 24, 34, "--.-°");
    s_cond = make_label(tile_wx, FONT_CN, 0x00c2ff, LV_ALIGN_TOP_LEFT, 210, 44, "加载中...");
    s_detail = make_label(tile_wx, FONT_CN_SM, 0x8ec5ff, LV_ALIGN_TOP_LEFT, 210, 74, " ");

    for (int i = 0; i < WEATHER_DAILY_DAYS; i++) {
        int dx = (i - 1) * 150;
        s_fore_date[i] = make_label(tile_wx, FONT_TINY, 0xffd479, LV_ALIGN_TOP_MID, dx, 130, "--");
        s_fore_cond[i] = make_label(tile_wx, FONT_CN_SM, 0xffd479, LV_ALIGN_TOP_MID, dx, 152, "--");
        s_fore_temp[i] = make_label(tile_wx, FONT_TINY, 0xffffff, LV_ALIGN_TOP_MID, dx, 178, "--");
    }

    s_upd = make_label(tile_wx, FONT_CN_SM, 0x6f86a6, LV_ALIGN_BOTTOM_RIGHT, -16, -8, "");

    /* radio page */
    radio_ui_build(tile_radio);

    /* IPTV page */
    lv_obj_t *tile_tv = lv_tileview_add_tile(tv, 3, 0, LV_DIR_HOR);
    tv_ui_build(tile_tv);

    /* settings page */
    lv_obj_t *tile_set = lv_tileview_add_tile(tv, 4, 0, LV_DIR_HOR);
    settings_ui_build(tile_set);

    /* The tiles come with the theme's opaque background; the screen already
     * paints the same colour, so every page redraw used to fill another
     * 480x284 rect for nothing (several ms per full-screen update). */
    for (uint32_t i = 0; i < lv_obj_get_child_count(tv); i++) {
        lv_obj_t *tile = lv_obj_get_child(tv, i);
        lv_obj_set_style_bg_opa(tile, LV_OPA_TRANSP, 0);
    }

    lv_timer_create(tick_cb, 1000, NULL);
    update_status();
    update_weather();
}
