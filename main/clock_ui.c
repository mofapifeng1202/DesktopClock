/*
 * Desktop clock UI: fixed status bar (battery / Wi-Fi) + a tileview with two
 * swipeable pages: big clock (NTP time) and weather (Open-Meteo, Chongqing).
 *
 * NOTE: LVGL's lv_label_set_text_fmt does not support %f, so all floating
 * point values are formatted with snprintf into a buffer first.
 */
